export type StringKey = keyof typeof STRINGS;

export const DEFAULT_LOCALE = 'bn-BD';
export const LOCALES = ['bn-BD', 'en'] as const;
export type AppLocale = (typeof LOCALES)[number];

export function isAppLocale(value: string): value is AppLocale {
  return (LOCALES as readonly string[]).includes(value);
}

export function translate(key: StringKey, locale: AppLocale): string {
  return STRINGS[key][locale === 'en' ? 'en' : 'bn'];
}

/** `bn-BD` → `bn`, which is what `@sbm/domain` and the API expect. */
export function baseLocale(locale: AppLocale): 'bn' | 'en' {
  return locale === 'en' ? 'en' : 'bn';
}
